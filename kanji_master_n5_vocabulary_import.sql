create temporary table kanji_n5_words on commit drop as
select
  word,
  (array_agg(romaji order by source_order))[1] as romaji,
  to_jsonb(array_agg(distinct target_kanji order by target_kanji)) as kanji_selection
from kanji_n5_source
group by word;

do $import$
declare
  owner_uuid uuid := 'REPLACE_WITH_YOUR_AUTH_USER_UUID'::uuid;
  updated_count integer;
  inserted_count integer;
begin
  if not exists (select 1 from auth.users where id = owner_uuid) then
    raise exception 'No auth.users row for %', owner_uuid;
  end if;

  update public.vocab as v
  set study_as_kanji = true,
      kanji_selection = source.kanji_selection,
      romaji = coalesce(nullif(v.romaji, ''), source.romaji)
  from kanji_n5_words as source
  where v.user_id = owner_uuid
    and v.kanji = source.word;
  get diagnostics updated_count = row_count;

  insert into public.vocab
    (user_id, kanji, romaji, study_as_kanji, kanji_selection)
  select
    owner_uuid, source.word, source.romaji, true, source.kanji_selection
  from kanji_n5_words as source
  where not exists (
    select 1
    from public.vocab as v
    where v.user_id = owner_uuid
      and v.kanji = source.word
  );
  get diagnostics inserted_count = row_count;

  raise notice 'Updated % existing words; inserted % new words.',
    updated_count, inserted_count;
end
$import$;

